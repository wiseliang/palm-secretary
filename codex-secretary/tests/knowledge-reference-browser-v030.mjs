import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { splitKnowledgeReference } from '../app/knowledge-reference.ts';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
const output = path.resolve('.local-workspace/knowledge-preview/qa-reference');
await mkdir(output, { recursive: true });
const calls = async () => (await readFile('.local-workspace/knowledge-preview/mock.jsonl', 'utf8').catch(() => '')).split('\n').filter(Boolean).map(line => JSON.parse(line));
const turnCount = async () => (await calls()).filter(call => call.method === 'turn/start').length;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
  assert.equal((await context.request.post('http://localhost:4520/api/auth/login', { data: { password: 'knowledge-preview' } })).status(), 200);
  const page = await context.newPage(); page.setDefaultTimeout(60_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const notePath = '读书笔记/让笔记真正有用.md';
  const url = `http://localhost:4520/?knowledge=${encodeURIComponent(notePath)}`;
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90_000 });
  await page.locator('.kb-article-header h1').waitFor();
  await page.evaluate(() => localStorage.setItem('palm:draft:default', '请保留我的原问题'));
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.kb-article-header h1').waitFor();
  const before = await turnCount();
  await page.getByRole('button', { name: '拿这篇问助手', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: path.join(output, 'desktop-preview.png') });
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await turnCount(), before);
  assert.ok(await page.locator('.kb').isVisible());
  await page.getByRole('button', { name: '拿这篇问助手', exact: true }).click();
  await page.getByRole('button', { name: '带入对话', exact: true }).click();
  await page.getByRole('region', { name: '待发送的知识库引用' }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: '任务内容' }).inputValue(), '请保留我的原问题');
  assert.equal(await turnCount(), before, 'Staging must never auto-send');
  await page.getByRole('textbox', { name: '任务内容' }).fill('请解释这一篇');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('region', { name: '待发送的知识库引用' }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: '任务内容' }).inputValue(), '请解释这一篇');
  await page.getByRole('button', { name: '移除知识库引用' }).click();
  assert.equal(await page.getByRole('textbox', { name: '任务内容' }).inputValue(), '请解释这一篇');
  assert.equal(await page.getByRole('region', { name: '待发送的知识库引用' }).count(), 0);
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.locator('.kb-prose > p').first().waitFor();
  const selected = await page.locator('.kb-prose > p').first().innerText();
  await page.locator('.kb-prose > p').first().evaluate(el => { const range = document.createRange(); range.selectNodeContents(el); const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range); });
  await page.getByRole('button', { name: '引用选中段落' }).click();
  await page.getByRole('button', { name: '带入对话', exact: true }).click();
  await page.getByRole('region', { name: '待发送的知识库引用' }).waitFor();
  const pending = splitKnowledgeReference(await page.evaluate(() => localStorage.getItem('palm:draft:default')));
  assert.equal(pending.reference.scope, 'selection'); assert.equal(pending.reference.content, selected);
  await page.getByRole('button', { name: '总结要点', exact: true }).click();
  await page.getByRole('region', { name: '待发送的知识库引用' }).getByText('查看引用内容', { exact: true }).click();
  await page.screenshot({ path: path.join(output, 'desktop-composer.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile-composer.png'), fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: path.join(output, 'mobile-dark.png'), fullPage: true });
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.waitForFunction(() => !localStorage.getItem('palm:pending-turn:default'));
  await page.getByRole('region', { name: '本次知识库引用' }).waitFor();
  await page.waitForTimeout(800);
  const turns = (await calls()).filter(call => call.method === 'turn/start');
  assert.equal(turns.length, before + 1, 'Exactly one user-triggered turn');
  const sent = splitKnowledgeReference(turns.at(-1).params.input[0].text);
  assert.equal(sent.reference.content, selected);
  assert.equal(sent.reference.scope, 'selection');
  assert.equal(await page.evaluate(() => localStorage.getItem('palm:draft:default')), null);
  const taskResponse = await context.request.get('http://localhost:4520/api/tasks?projectId=default');
  const tasks = (await taskResponse.json()).tasks;
  const task = tasks.find(task => task.threadId === turns.at(-1).params.threadId);
  assert.ok(task);
  const history = await (await context.request.get(`http://localhost:4520/api/threads/${task.threadId}?projectId=default`)).json();
  const userText = history.thread.turns.at(-1).items.find(item => item.type === 'userMessage').text;
  assert.equal(splitKnowledgeReference(userText).reference.content, selected);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.querySelector('.topbar'));
  await page.evaluate(task => { window.__PALM_OPEN_TASK__ = { projectId: 'default', threadId: task.threadId }; window.dispatchEvent(new CustomEvent('palm-open-task', { detail: window.__PALM_OPEN_TASK__ })); }, task);
  await page.getByRole('region', { name: '本次知识库引用' }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['cancel/no auto-send', 'whole note', 'preserve question', 'draft reload', 'remove', 'selection', 'source snapshot sent', 'single turn', 'history recovery', 'mobile/dark'], screenshots: output }));
} finally { await browser.close(); }


import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = path.resolve('.local-workspace/knowledge-preview/qa');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
  const login = await context.request.post('http://localhost:4520/api/auth/login', { data: { password: 'knowledge-preview' } });
  assert.equal(login.status(), 200);
  const page = await context.newPage();
  page.setDefaultTimeout(60000); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:4520/?knowledge=', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('.kb-recent button').first().waitFor();
  assert.equal(await page.getByText('AGENTS.md', { exact: true }).count(), 0);
  await page.screenshot({ path: path.join(output, 'desktop-home.png'), fullPage: true });
  await page.getByRole('searchbox', { name: '搜索知识库' }).fill('付诸实践');
  await page.locator('.kb-search-results button').waitFor();
  assert.equal(await page.locator('.kb-search-results button').count(), 1);
  await page.locator('.kb-search-results button').click();
  await page.locator('.kb-article-header h1').filter({ hasText: '每周回顾' }).waitFor();
  await page.getByRole('link', { name: '返回阅读笔记' }).click();
  await page.locator('.kb-article-header h1').filter({ hasText: '让笔记真正有用' }).waitFor();
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.kb-alert').count(), 0);
  assert.equal(await page.locator('.kb-callout').count(), 1);
  assert.equal(await page.locator('.kb-prose table').count(), 1);
  assert.ok(await page.locator('.kb-prose code').filter({ hasText: '[[代码里的双链不应转换]]' }).count());
  assert.equal(await page.evaluate(() => window.knowledgeXss), undefined);
  await page.waitForFunction(() => [...document.querySelectorAll('.kb-prose img')].every(img => img.complete && img.naturalWidth > 0));
  await page.getByRole('searchbox', { name: '搜索知识库' }).fill('');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'desktop-reading.png'), fullPage: true });
  await page.reload({ waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('.kb-article-header h1').filter({ hasText: '让笔记真正有用' }).waitFor();
  await page.goBack({ waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('.kb-article-header h1').filter({ hasText: '每周回顾' }).waitFor();
  await page.getByRole('link', { name: '尚未同步的笔记' }).click();
  await page.locator('.kb-alert').filter({ hasText: '不存在' }).waitFor();
  await page.getByRole('button', { name: '关闭提示' }).click();
  await page.getByRole('link', { name: '返回阅读笔记' }).click();
  await page.locator('.kb-article-header h1').filter({ hasText: '让笔记真正有用' }).waitFor();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'desktop-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'light' });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.ok(await page.locator('.kb-mobile-directory').isVisible());
  assert.ok(!(await page.locator('.kb-sidebar').isVisible()));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile-reading.png'), fullPage: true });
  await page.getByRole('button', { name: '目录', exact: true }).click();
  await page.getByRole('searchbox', { name: '搜索知识库' }).fill('不存在的搜索');
  await page.getByText('找到 0 篇笔记').waitFor();
  await page.screenshot({ path: path.join(output, 'mobile-search.png'), fullPage: true });
  await page.getByRole('searchbox', { name: '搜索知识库' }).fill('每周回顾');
  await page.locator('.kb-search-results button').first().click();
  assert.ok(!(await page.locator('.kb-sidebar').isVisible()));
  await page.getByRole('button', { name: '刷新知识库' }).click();
  await page.locator('.kb-article-header h1').waitFor();
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['search', 'wikilinks', 'Chinese anchors', 'table/callout', 'images', 'XSS inert', 'refresh deep link', 'back', 'missing link', 'dark mode', 'mobile directory', '320px overflow'], screenshots: output }));
} finally { await browser.close(); }



import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createSession } from '../dist-server/auth.js';
import { SessionStore } from '../dist-server/session-store.js';
import { createDownloadTicket, verifyDownloadTicket, downloadRange, downloadOrigin } from '../dist-server/download-ticket.js';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const secret = 'test-only-secret';
const origin = 'https://download.example.test';
const session = createSession(secret, 1);
const now = Date.now();
const token = createDownloadTicket(secret, session, 'project', 'outbox/成果.zip', origin, now);
const value = verifyDownloadTicket(token, secret, origin, now);
assert.equal(value.path, 'outbox/成果.zip');
assert.equal(value.sessionHash, createHash('sha256').update(session).digest('hex'));
assert.equal(Buffer.from(token.split('.')[0], 'base64url').toString().includes(session), false);
for (const bad of [undefined, token + '.extra', token + 'x', 'bad']) assert.equal(verifyDownloadTicket(bad, secret, origin, now), undefined);
assert.equal(verifyDownloadTicket(token, 'wrong', origin, now), undefined);
assert.equal(verifyDownloadTicket(token, secret, 'https://wrong.test', now), undefined);
assert.equal(verifyDownloadTicket(token, secret, origin, now + 120001), undefined);
assert.equal(downloadOrigin(''), undefined);
assert.throws(() => downloadOrigin('http://example.test'));
assert.throws(() => downloadOrigin('https://example.test/path'));
assert.deepEqual(downloadRange('bytes=2-5', 10), {start:2,end:5});
assert.deepEqual(downloadRange('bytes=-3', 10), {start:7,end:9});
assert.deepEqual(downloadRange('bytes=2-', 10), {start:2,end:9});
assert.equal(downloadRange('bytes=10-', 10), false);
assert.equal(downloadRange('bytes=0-1,4-5', 10), false);
assert.equal(downloadRange('bytes=-0', 10), false);
assert.equal(downloadRange(undefined, 0), undefined);
const directory = await mkdtemp(path.join(os.tmpdir(), 'palm-ticket-test-'));
try {
  const store = new SessionStore(path.join(directory, 'revoked.json'), secret);
  await store.initialize();
  assert.equal(store.validDownloadReference(value.sessionHash, value.expiresAt), true);
  await store.revoke(session);
  assert.equal(store.validDownloadReference(value.sessionHash, value.expiresAt), false);
} finally { await rm(directory, {recursive:true,force:true}); }
console.log('DOWNLOAD_TICKET_OK');
